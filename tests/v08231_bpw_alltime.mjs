import assert from 'node:assert/strict';
import {TEAMS,SHOTS,DEFAULT_OPTIONS,rosterFor} from '../src/data.js';
import {installExpansion,avatarFor} from '../src/expanded.js';
import {installContinentalClubs} from '../src/continental.js';
import {installBPWWorldCups,BPW_YEARS,historicalPersonKey} from '../src/bpw_world_cups.js';
import {installBPWAllTime,BPW_ALLTIME_ID,BPW_ALLTIME_SELECTION} from '../src/bpw_alltime.js';
import {safePlan,validatePlan} from '../src/tactics.js';
import {overallForPosition} from '../src/stats.js';
import {countryCode,isClub,teamIdentity} from '../src/identity.js';
import {GameEngine} from '../src/engine.js';
assert.equal(BPW_ALLTIME_SELECTION.length,12);
assert.deepEqual(BPW_ALLTIME_SELECTION.map(p=>p[2]),['GK','GK','DF','DF','DF','MF','MF','MF','MF','FW','FW','FW']);
assert.deepEqual(BPW_ALLTIME_SELECTION.map(p=>p[3]),[99,98,99,99,98,99,99,99,99,99,99,99]);
assert.deepEqual(BPW_ALLTIME_SELECTION.map(p=>p[0]),['Lev Yashin','Gianluigi Buffon','Franz Beckenbauer','Paolo Maldini','Sergio Ramos','Diego Maradona','Zinedine Zidane','Johan Cruyff','Lionel Messi','Pelé','Cristiano Ronaldo','Ronaldo Nazário']);
installExpansion(TEAMS,SHOTS);installContinentalClubs(TEAMS,SHOTS);
const legacy=TEAMS.map(t=>t.id);
assert.equal(legacy.length,216);
const originalBPW=installBPWWorldCups(TEAMS,SHOTS,avatarFor);
assert.equal(originalBPW.length,6);
const preserved=TEAMS.map(t=>t.id);
const all=installBPWAllTime(TEAMS,SHOTS,avatarFor);
assert.equal(all.id,BPW_ALLTIME_ID);
assert.equal(all.index,222);
assert.equal(TEAMS.length,223);
assert.deepEqual(TEAMS.slice(0,222).map(t=>t.id),preserved,'original club and six World Cup indices unchanged');
assert.equal(installBPWAllTime(TEAMS,SHOTS,avatarFor),all,'idempotent team registration');
assert.equal(TEAMS.length,223);
assert.equal(TEAMS.filter(t=>t.group==='bpw_worldcup').length,6);
assert.equal(TEAMS.filter(t=>t.group==='bpw_alltime').length,1);
assert.deepEqual(originalBPW.map(t=>t.worldCupYear),BPW_YEARS);
assert.equal(countryCode(all),null,'mixed nationality does not claim one country');
assert(isClub(all),'render original crest');
assert.match(teamIdentity(all),/crestGraphic/);
const roster=rosterFor(all.index);
assert.equal(roster.length,12);
const counts={GK:0,DF:0,MF:0,FW:0};
for(const [i,p] of roster.entries()){
 const [name,nationality,role,rating]=BPW_ALLTIME_SELECTION[i];
 assert.equal(p.id,`${BPW_ALLTIME_ID}_${i}`);
 assert.deepEqual([p.name,p.nationality,p.role,p.legendaryRating,p.rating],[name,nationality,role,rating,rating]);
 assert.equal(p.variantOf,historicalPersonKey(name));
 assert(!p.canonicalId,'unverified DOB must not force identity merge');
 assert.equal(p.age,undefined,'do not fabricate historical prime-era ages');
 assert.match(p.ratingSource,/user-selected legendary/);
 assert(p.avatar?.skin && p.avatar?.hair);
 assert.equal(typeof overallForPosition(p,role),'number');
 counts[role]++;
}
assert.deepEqual(counts,{GK:2,DF:3,MF:4,FW:3});
assert.equal(new Set(roster.map(p=>p.id)).size,12);
assert.equal(new Set(roster.map(p=>p.nationality)).size,9);
const plan=safePlan(null,roster,all.index);
assert.deepEqual(validatePlan(plan,roster,all.index),plan);
assert.equal(roster[plan.lineup[0]].role,'GK');
const fakeInput={state:[{},{}],poll(){},just(){return false}};
const match=new GameEngine({...DEFAULT_OPTIONS,weather:'Clear'},fakeInput);
for(const side of [0,1]){
 match.init({home:side===0?all.index:0,away:side===1?all.index:0,options:{...DEFAULT_OPTIONS,weather:'Clear'}});
 assert.equal(match.rosters[side].length,12);
 assert(match.players.some(p=>p.t===side&&p.keeper&&p.src.role==='GK'));
}
console.log('PASS v0.8.23.1 all-time: all 12 exact player/name/country/role/card-rating entries, formation, match both sides, team indexes and idempotence');
