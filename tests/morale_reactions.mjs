import assert from 'node:assert/strict';
import {GameEngine,WORLD} from '../src/engine.js';
import {TEAMS,SHOTS,DEFAULT_OPTIONS} from '../src/data.js';
import {installExpansion} from '../src/expanded.js';
import {installContinentalClubs} from '../src/continental.js';
import {TEAM_TALKS,personalityOf,reactToTalk,moraleFactor,moodLabel} from '../src/morale.js';
installExpansion(TEAMS,SHOTS);installContinentalClubs(TEAMS,SHOTS);
const input={state:[{},{}],poll(){},just(){return false}};
const make=()=>{const g=new GameEngine({...DEFAULT_OPTIONS,weather:'Clear'},input);g.init({home:0,away:9,options:{...DEFAULT_OPTIONS,weather:'Clear'}});return g};
const game=make();
assert.equal(game.players.length,12);
assert.equal(Object.keys(TEAM_TALKS).length,5);
assert.equal(Object.keys(game.moraleLedger[0]).length,12);
assert.ok(game.teamMorale(0)>0);
// Team talk can boost some players and make others angry, with deterministic reactions.
let people=game.rosters[0];
const reactions=people.map(p=>reactToTalk(55,p,'joke'));
assert.ok(reactions.some(p=>p.backfire),'Jokes must sometimes backfire');
assert.ok(reactions.some(p=>p.delta>0),'Jokes must sometimes inspire');
assert.deepEqual(reactions,people.map(p=>reactToTalk(55,p,'joke')),'stable personality choices');
assert.ok(people.every(p=>['sensitive','bold','playful','disciplined'].includes(personalityOf(p))));
const baseSpeed=game.playerSpeed(game.player(0,3));
const report=game.applyTeamTalk(0,'joke','pregame');
assert.ok(report.backfires>0&&report.positive>0);
assert.throws(()=>game.applyTeamTalk(0,'encourage','pregame'),/already/);
assert.throws(()=>game.applyTeamTalk(1,'not_a_talk','pregame'),/Invalid/);
assert.notEqual(game.teamMorale(0),55);
let player=game.player(0,3);
player.morale=15;const low=game.playerSpeed(player);
player.morale=90;const high=game.playerSpeed(player);
assert.ok(high>low*1.1,`Morale should affect performance low=${low} high=${high}`);
assert.ok(moraleFactor(90)>moraleFactor(10));
assert.equal(moodLabel(10),'DESPAIR');
// Changes survive substitutions and kickoff while preserving bench player state.
player.morale=game.moraleLedger[0][player.src.id];
const keptName=player.src.id,keptMorale=player.morale;
game.resetKickoff(0);
assert.equal(game.player(0,3).src.id,keptName);
assert.equal(game.player(0,3).morale,keptMorale);
const before=game.teamMorale(0);
// Trigger a real end-line goal and verify reactions for on-field & bench players.
game.ball.owner=null;game.ball.attacker=0;game.ball.x=WORLD.field.x+WORLD.field.w+9;game.ball.y=(WORLD.goalTop+WORLD.goalBottom)/2;game.ball.z=0;game.ball.vx=120;game.ball.vy=0;game.ball.canCollect=0;
game.updateBall(.016);
assert.equal(game.score[0],1);
assert.ok(game.teamMorale(0)>before,'Scoring improves team mood');
assert.ok(game.teamMorale(1)<55,'Conceding damages morale');
assert.equal(game.player(1,2).action,'cry');
assert.ok(game.player(1,2).cryTimer>2);
assert.equal(game.player(0,2).action,'celebrate');
assert.ok(game.celebrationStyle>=0&&game.celebrationStyle<=4);
const moodAfterGoal=game.player(1,2).morale;
for(let i=0;i<130;i++)game.update(.03);
assert.equal(game.celebration,0);
assert.equal(game.player(1,2).morale,moodAfterGoal,'Morale must survive goal kickoff');
// Talk can happen once per team at half-time, not during the match.
assert.throws(()=>game.applyTeamTalk(0,'focus','halftime'),/window closed/);
game.half=2;game.clock=0;game.matchState='paused';
const beforeHalftime=game.teamMorale(0);
const afterHalftime=game.applyTeamTalk(0,'encourage','halftime');
assert.equal(afterHalftime.phase,'halftime');
assert.notEqual(beforeHalftime,game.teamMorale(0));
assert.throws(()=>game.applyTeamTalk(0,'focus','halftime'),/already/);
console.log('v0.7.3 MORALE/REACTIONS PASS • reactions/backfires • speed • scoring/crying • persistence • half-time limits • 216 teams preserved');
