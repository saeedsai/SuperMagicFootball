'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const src=fs.readFileSync('src/modules/engine.js','utf8');
test('named Magic Trick resolution uses the visible first-touch screen reader; ordinary Dribble Styles stay separate',()=>{
 const magicStart=src.indexOf('tryMagicTrick(p){'),magicEnd=src.indexOf('updateSpinBumpFx(p,dt){',magicStart);
 const dribbleStart=src.indexOf('tryDribbleTrick(p,byAI=false){'),dribbleEnd=src.indexOf('// Safety is evaluated at release time;',dribbleStart);
 assert.ok(magicStart>=0&&magicEnd>magicStart,'named Magic Trick resolver available');
 assert.ok(dribbleStart>=0&&dribbleEnd>dribbleStart,'ordinary Dribble Style resolver available');
 const magic=src.slice(magicStart,magicEnd),dribble=src.slice(dribbleStart,dribbleEnd);
 assert.ok(magic.includes("const trickRivals=id==='lightning'?lightningTargets:readyCounterTargets"));
 assert.ok(magic.includes("const counterRead=typeof defensiveMagicTrickReadTarget==='function'?defensiveMagicTrickReadTarget(p,trickRivals,true,this.ball):null"));
 assert.match(magic,/const defenderRead=clamp\(\.07\+stat\(counterRead\.defender,'defence'\)\*\.0017,\.07,\.24\)/);
 assert.match(magic,/const attackerDribbling=clamp\(stat\(p,'dribbling'\),1,100\)/);
 assert.match(magic,/const dribblingResistance=\(attackerDribbling-50\)\*\.0012/);
 assert.match(magic,/return clamp\(defenderRead-dribblingResistance,\.04,\.28\)/);
 assert.match(magic,/const screenRead=id!=='lightning'&&screenReadChance>0&&Math\.random\(\)<screenReadChance/);
 assert.match(magic,/screenRead/);
 assert.match(magic,/if\(screenRead&&counterRead\?\.defender\)\{\s*counterRead\.defender\.magicReadCueTimer=Math\.max\(Number\(counterRead\.defender\.magicReadCueTimer\)\|\|0,\.48\);\s*counterRead\.defender\.magicReadCounterpressTimer=Math\.max\(Number\(counterRead\.defender\.magicReadCounterpressTimer\)\|\|0,\.42\);\s*\}/);
 assert.doesNotMatch(dribble,/defensiveMagicTrickReadTarget|readBonus/);
});
