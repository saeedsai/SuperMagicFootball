const { test } = require('node:test');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const load = () => import(pathToFileURL(path.resolve('src/modules/lan-host-lobby.js')).href);
const roomId = 'room_12345678';
const request = requestId => ({ version: 1, type: 'join-request', roomId, requestId });
test('LAN host has one guest seat and must explicitly approve joining', async () => {
  const { createLanHostLobby } = await load();
  const lobby = createLanHostLobby({ roomId });
  assert.equal(lobby.receive(request('request_12345678')), true);
  assert.equal(lobby.receive(request('request_87654321')), true);
  assert.equal(lobby.guest(), null);
  assert.equal(lobby.decide('request_12345678', true).type, 'join-accept');
  assert.deepEqual(lobby.guest(), { requestId: 'request_12345678' });
  assert.equal(lobby.decide('request_87654321', true), null);
  assert.equal(lobby.receive(request('request_abcdefgh')), false);
  assert.equal(lobby.decide('request_87654321', false).type, 'join-reject');
  assert.equal(lobby.disconnect('request_87654321'), false);
  assert.equal(lobby.disconnect('request_12345678'), true);
  assert.equal(lobby.guest(), null);
  assert.equal(lobby.receive(request('request_12345678')), false);
  assert.equal(lobby.receive(request('request_abcdefgh')), true);
  assert.equal(lobby.decide('request_abcdefgh', true).type, 'join-accept');
});
test('LAN host rejects invalid approval, expired requests and closed lobby', async () => {
  const { createLanHostLobby } = await load();
  let now = 0;
  const lobby = createLanHostLobby({ roomId, ttlMs: 1000, now: () => now });
  assert.equal(lobby.receive(request('request_12345678')), true);
  assert.equal(lobby.decide('request_12345678', 'yes'), null);
  now = 1000;
  assert.equal(lobby.decide('request_12345678', true), null);
  assert.equal(lobby.receive(request('request_87654321')), true);
  lobby.close();
  assert.deepEqual(lobby.pending(), []);
  assert.equal(lobby.receive(request('request_abcdefgh')), false);
  assert.equal(lobby.decide('request_87654321', true), null);
  assert.equal(lobby.disconnect('request_87654321'), false);
  assert.equal(lobby.guest(), null);
  assert.throws(() => createLanHostLobby({ roomId: 'bad' }), TypeError);
});
