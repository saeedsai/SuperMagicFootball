import assert from 'node:assert/strict';
import {shotReleaseContext,MatchOpportunityTracker} from '../src/match_telemetry.js';
const player=(t,x,y,keeper=false,stun=0)=>({t,x,y,keeper,stun,fatigue:.35});
const keeper=player(1,3340,760,true);
const defender=player(1,1990,760);
const game={players:[player(0,1960,760),defender,keeper,player(1,1970,760,false,1)],ball:{vx:700,vy:0,owner:null}};
const event={type:'kick',player:game.players[0],kind:'shot',origin:{x:1960,y:760,z:20},targetY:690};
const original=JSON.stringify(game);
const c=shotReleaseContext(event,game);
assert.equal(c.nearestDefenderDistance,30);
assert.equal(c.pressureBand,'close');
assert.equal(c.nearbyDefenders,1,'stunned defender excluded');
assert.equal(c.keeperLateralOffset,70);
assert.equal(c.ballSpeed,700);
assert.equal(c.releaseHeight,20);
assert.equal(JSON.stringify(game),original,'snapshot must not alter gameplay');
assert.equal(shotReleaseContext({...event,origin:{x:NaN,y:700}},game),null);
assert.equal(shotReleaseContext(event,null),null);
const tracker=new MatchOpportunityTracker();
tracker.onEvent(event,game);tracker.onEvent({type:'save',player:keeper,saveType:'dive'});
assert.equal(tracker.attempts[0].releaseContext.pressureBand,'close');
assert.equal(tracker.attempts[0].outcome,'keeper_save');
assert.equal(tracker.report().shotReleasePressureCounts.close,1);
defender.x=2500;keeper.y=860;
const n=shotReleaseContext(event,game);
assert.equal(n.pressureBand,'open');assert.equal(n.keeperLateralOffset,170);
const right={...event,player:player(1,1830,760),origin:{x:1830,y:760,z:0}};
const left={players:[player(0,300,760,true),player(0,1250,760),right.player],ball:{vx:-550,vy:0}};
assert.equal(shotReleaseContext(right,left).goalDistance,1680);
const absent={players:[event.player],ball:{vx:0,vy:0}};
assert.equal(shotReleaseContext(event,absent).pressureBand,'no_active_defender');
tracker.onEvent({type:'kick',player:game.players[0],kind:'pass',origin:event.origin},game);
assert.equal(tracker.report().shotReleasePressureCounts.close,1,'passes excluded from shot-pressure buckets');
console.log('PASS v0.8.24.12 release-pressure context, inertness, mirroring, and legacy compatibility');
